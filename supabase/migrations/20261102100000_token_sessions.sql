-- Expand token storage without removing the legacy plaintext columns yet.
-- Existing organiser links remain valid while the application switches to hashes.
create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;

alter table communities add column if not exists admin_token_hash text;
alter table events add column if not exists admin_token_hash text;

update communities
set admin_token_hash = encode(extensions.digest(admin_token, 'sha256'), 'hex')
where admin_token_hash is null and admin_token is not null;

update events
set admin_token_hash = encode(extensions.digest(admin_token, 'sha256'), 'hex')
where admin_token_hash is null and admin_token is not null;

-- If legacy community credentials were reused, retain them on one deterministic community only.
with ranked_communities as (
  select id, row_number() over (partition by admin_token_hash order by id) as token_rank
  from communities
  where admin_token_hash is not null
)
update communities as c
set admin_token_hash = null
from ranked_communities as ranked
where ranked.id = c.id
  and ranked.token_rank > 1;

-- Old seed data reused the community token on every demo event. Promote that
-- credential to community scope and remove any other event hashes shared with communities.
update events as e
set admin_token_hash = null
where exists (
  select 1 from communities as c where c.admin_token_hash = e.admin_token_hash
);

-- Reused event tokens cannot represent multiple strict event scopes. Keep one
-- deterministic event binding so auth lookup remains unambiguous.
with ranked_events as (
  select id, row_number() over (partition by admin_token_hash order by id) as token_rank
  from events
  where admin_token_hash is not null
)
update events as e
set admin_token_hash = null
from ranked_events as ranked
where ranked.id = e.id
  and ranked.token_rank > 1;

create unique index if not exists communities_admin_token_hash_idx on communities(admin_token_hash) where admin_token_hash is not null;
create unique index if not exists events_admin_token_hash_idx on events(admin_token_hash) where admin_token_hash is not null;

-- New application-created tokens are generated by the server and only their hashes are stored.
alter table communities alter column admin_token drop not null;
alter table events alter column admin_token drop not null;

-- Keep the legacy database defaults while old app instances still rely on them.
-- New hash-based writes clear the default-generated plaintext before storage;
-- old app writes continue receiving their token while the trigger backfills its hash.
create or replace function public.sync_admin_token_hash()
returns trigger
language plpgsql
set search_path = public, extensions
as $$
begin
  if tg_op = 'INSERT' then
    if new.admin_token_hash is not null then
      new.admin_token := null;
    elsif new.admin_token is not null then
      new.admin_token_hash := encode(extensions.digest(new.admin_token, 'sha256'), 'hex');
    end if;
    return new;
  end if;

  if tg_argv[0] = 'legacy' then
    if new.admin_token is null then
      new.admin_token_hash := null;
    else
      new.admin_token_hash := encode(extensions.digest(new.admin_token, 'sha256'), 'hex');
    end if;
  elsif tg_argv[0] = 'hash' then
    new.admin_token := null;
  end if;
  return new;
end;
$$;

drop trigger if exists communities_admin_token_hash_insert on public.communities;
create trigger communities_admin_token_hash_insert
before insert on public.communities
for each row execute function public.sync_admin_token_hash('insert');
drop trigger if exists communities_admin_token_hash_legacy_update on public.communities;
create trigger communities_admin_token_hash_legacy_update
before update of admin_token on public.communities
for each row execute function public.sync_admin_token_hash('legacy');
drop trigger if exists communities_admin_token_hash_new_update on public.communities;
create trigger communities_admin_token_hash_new_update
before update of admin_token_hash on public.communities
for each row execute function public.sync_admin_token_hash('hash');

drop trigger if exists events_admin_token_hash_insert on public.events;
create trigger events_admin_token_hash_insert
before insert on public.events
for each row execute function public.sync_admin_token_hash('insert');
drop trigger if exists events_admin_token_hash_legacy_update on public.events;
create trigger events_admin_token_hash_legacy_update
before update of admin_token on public.events
for each row execute function public.sync_admin_token_hash('legacy');
drop trigger if exists events_admin_token_hash_new_update on public.events;
create trigger events_admin_token_hash_new_update
before update of admin_token_hash on public.events
for each row execute function public.sync_admin_token_hash('hash');

create table if not exists access_tokens (
  token_hash text primary key,
  token_type text not null check (token_type in ('session', 'llm')),
  event_id uuid references events(id) on delete cascade,
  community_id uuid references communities(id) on delete cascade,
  llm boolean not null default false,
  expires_at timestamptz not null,
  created_at timestamptz not null default now(),
  check ((event_id is not null) <> (community_id is not null)),
  check (llm = (token_type = 'llm'))
);

create index if not exists access_tokens_expires_at_idx on access_tokens(expires_at);
create index if not exists access_tokens_event_idx on access_tokens(event_id) where event_id is not null;
create index if not exists access_tokens_community_idx on access_tokens(community_id) where community_id is not null;

-- Session and LLM token hashes are only accessed by the server-side service role.
revoke all privileges on table public.access_tokens from anon, authenticated;
alter table public.access_tokens enable row level security;
grant all privileges on table public.access_tokens to service_role;
